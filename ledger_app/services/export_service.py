class NumberedCanvas(canvas.Canvas):
    """Custom canvas implementation to add headers and footers with accurate page counts."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []
        self.load_business_settings()

    def load_business_settings(self):
        """Loads business configurations dynamically from settings.json."""
        self.biz_name = "Jalaj Ledger"
        self.owner_name = "Jalaj Singhal"
        self.phone = "+91XXXXXXXXXX"
        self.address = "Business Address"
        
        if os.path.exists("settings.json"):
            try:
                with open("settings.json", "r") as f:
                    data = json.load(f)
                    self.biz_name = data.get("name") or data.get("business_name") or "Jalaj Ledger"
                    self.owner_name = data.get("owner_name") or "Jalaj Singhal"
                    self.phone = data.get("business_phone") or data.get("phone") or "+91XXXXXXXXXX"
                    self.address = data.get("address") or "Business Address"
            except Exception as e:
                print(f"Error loading settings in NumberedCanvas: {e}")

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        
        # 1. Running Header
        self.setFont("Helvetica-Bold", 11)
        self.setFillColor(colors.HexColor("#0F172A"))  # Slate 900
        self.drawString(54, 760, self.biz_name.upper())
        
        self.setFont("Helvetica", 8.5)
        self.setFillColor(colors.HexColor("#64748B"))  # Slate 500
        self.drawString(54, 746, f"Owner: {self.owner_name}")
        self.drawString(54, 734, f"Phone: {self.phone}")
        self.drawString(54, 722, f"Address: {self.address}")
        
        # Separator line
        self.setStrokeColor(colors.HexColor("#E2E8F0"))  # Slate 200
        self.setLineWidth(1)
        self.line(54, 712, 558, 712)
        
        # 2. Running Footer
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 55, 558, 55)
        
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#94A3B8"))  # Slate 400
        self.drawString(54, 42, f"{self.biz_name} | Phone: {self.phone}")
        self.drawString(54, 30, "Generated by Ledger Management System")
        
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 42, page_text)
        
        self.restoreState()


